HEADER = "/* Generated by tools/art/build_art.py. Do not edit. */\n"


def load(path):
    return Image.open(path).convert("RGBA")


def write_sprite(graphics, name, frames, check_edges=True, palette=None):
    palette, pixels, size = gba.sprite_sheet(frames, check_edges, palette)
    write_sheet(graphics, name, pixels, size, palette, frames[0].size[1])
    return palette, pixels


def write_sheet(graphics, name, pixels, size, palette, height):
    gba.write_bmp(os.path.join(graphics, name + ".bmp"), size, pixels, palette)
    gba.write_json(os.path.join(graphics, name + ".json"),
                   {"type": "sprite", "height": height, "bpp_mode": "bpp_4", "colors_count": 16})


def split_frames(pixels, w, frame_h, top_h):
    """Split every frame of a vertical sheet into its top rows and the rest."""
    top, bottom = bytearray(), bytearray()
    for f in range(len(pixels) // (w * frame_h)):
        base = f * w * frame_h
        top += pixels[base:base + w * top_h]
        bottom += pixels[base + w * top_h:base + w * frame_h]
    return top, bottom


def drawn_box(pixels, w, frame_h, feet):
    """The opaque extent of every frame in a sheet, around the feet: (left, top, right, bottom)."""
    xs = [i % w for i, v in enumerate(pixels) if v]
    ys = [(i // w) % frame_h for i, v in enumerate(pixels) if v]
    return min(xs) - feet[0], min(ys) - feet[1], max(xs) + 1 - feet[0], max(ys) + 1 - feet[1]


def logo_frames(art, frame_w, frame_h, count):
    """Centre the logo art on count frames laid side by side, and return them left to right."""
    canvas = Image.new("RGBA", (frame_w * count, frame_h), (0, 0, 0, 0))
    canvas.alpha_composite(art, ((canvas.width - art.width) // 2, (frame_h - art.height) // 2))
    return [canvas.crop((i * frame_w, 0, (i + 1) * frame_w, frame_h)) for i in range(count)]


def room_arrays(room, px):
    """A quantized room image -> (w, h, h8, tiles, cells), with the height padded to whole tile rows."""
    w, h = room.size
    h8 = (h + 7) // 8 * 8
    tiles, cells = gba.room_tiles(bytearray(px) + bytearray(w * (h8 - h)), w, h8)
    if len(tiles) > gba.ROOM_TILE_LIMIT:
        raise gba.ArtError("room has %d unique tiles (limit %d)" % (len(tiles), gba.ROOM_TILE_LIMIT))
    return w, h, h8, tiles, cells


def write_rooms(gen, out_dir, rooms):
    """rooms: a list of (name, image, palette, index pixels). Writes gen/rooms.{h,c,json}: each room's tiles and
    map behind one room_data table entry (room_<name>), and out/room_<name>.png. Returns {name: tile count}."""
    arrays = {}
    os.makedirs(out_dir, exist_ok=True)
    for name, room, palette, px in rooms:
        arrays[name] = room_arrays(room, px)
        image = Image.new("RGB", room.size)
        image.putdata([palette[v] for v in px])
        image.save(os.path.join(out_dir, "room_%s.png" % name))
    with open(os.path.join(gen, "rooms.h"), "w") as f:
        f.write(HEADER + "#ifndef ROOMS_H\n#define ROOMS_H\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
                "typedef struct {\n    const uint32_t* tiles;\n    const uint16_t* map;\n"
                "    uint16_t w, h, w_cells, h_cells, tile_count;\n} room_data;\n\n")
        for name, *_ in rooms:
            f.write("extern const room_data room_%s;\n" % name)
        f.write("\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n")
    with open(os.path.join(gen, "rooms.c"), "w") as f:
        f.write(HEADER + "#include \"rooms.h\"\n")
        for name, *_ in rooms:
            w, h, h8, tiles, cells = arrays[name]
            words = []
            for t in tiles:
                words += ["0x%08x" % int.from_bytes(t[k:k + 4], "little") for k in range(0, 64, 4)]
            f.write("\n__attribute__((aligned(4))) static const uint32_t room_%s_tiles[%d] = {\n" % (name, len(words)))
            for k in range(0, len(words), 16):
                f.write("    " + ", ".join(words[k:k + 16]) + ",\n")
            f.write("};\n\nstatic const uint16_t room_%s_map[%d] = {\n" % (name, len(cells)))
            for k in range(0, len(cells), 32):
                f.write("    " + ", ".join(str(c) for c in cells[k:k + 32]) + ",\n")
            f.write("};\n\nconst room_data room_%s = { room_%s_tiles, room_%s_map, %d, %d, %d, %d, %d };\n"
                    % (name, name, name, w, h, w // 8, h8 // 8, len(tiles)))
    with open(os.path.join(gen, "rooms.json"), "w") as f:
        json.dump({name: {"w": arrays[name][0], "h": arrays[name][1], "tiles": len(arrays[name][3]),
                          "map": arrays[name][4]} for name, *_ in rooms}, f)
    return {name: len(arrays[name][3]) for name, *_ in rooms}


def write_sprites_h(gen, names, hands, dev_names, player_head, dev_head):
    offs, per_dir = charspec.offsets(charspec.PLAYER_ANIMS)
    dev_offs, _ = charspec.offsets(charspec.DEV_ANIMS)
    counts = {label: n for label, _, _, n in charspec.PLAYER_ANIMS}
    fx, fy = charspec.FEET
    lines = [HEADER, "#ifndef SPRITES_H\n#define SPRITES_H\n\n",
             "#define PLAYER_FRAME_W %d\n#define PLAYER_FRAME_H %d\n#define PLAYER_TOP_H 64\n" % charspec.PLAYER_FRAME,
             "#define SPRITE_FEET_X %d\n#define SPRITE_FEET_Y %d\n" % charspec.FEET,
             "#define DEV_FEET_X %d\n#define DEV_FEET_Y %d\n" % charspec.DEV_FEET,
             "#define PLAYER_HEAD %d\n#define DEV_HEAD %d\n" % (player_head, dev_head),
             "#define PLAYER_FRAMES_PER_DIR %d\n" % per_dir,
             "#define PLAYER_IDLE %d\n#define PLAYER_IDLE_N %d\n" % (offs["idle"], counts["idle"]),
             "#define PLAYER_WALK %d\n#define PLAYER_WALK_N %d\n" % (offs["walk"], counts["walk"]),
             "#define PLAYER_CARRY_IDLE %d\n#define PLAYER_CARRY_WALK %d\n" % (offs["carry_idle"], offs["carry_walk"]),
             "#define DEV_TYPE %d\n#define DEV_TYPE_N %d\n#define DEV_TIRED %d\n" % (
                 dev_offs["type"], charspec.DEV_ANIMS[0][3], dev_offs["tired"]),
             "#define ICON_BUBBLE 0\n#define ICON_CHAI 1\n#define ICON_ARROW_DOWN 2\n#define ICON_ARROW_LEFT 3\n"
             "#define ICON_ARROW_RIGHT 4\n#define ICON_ARROW_UP 5\n#define METER_FRAMES 12\n",
             "#define BUG_FRAMES 3\n#define SPARK_FRAMES 2\n#define RAIN_FRAMES 3\n",
             "#define ICON_LAPTOP 6\n#define ICON_BTN_A 7\n#define ICON_BTN_B 8\n",
             "#define CROWD_FEET_X %d\n#define CROWD_FEET_Y %d\n#define CROWD_WALK_N %d\n\n" % (
                 charspec.CROWD_FEET + (charspec.CROWD_ANIMS[0][3],))]
    for axis, feet in ((0, fx), (1, fy)):
        values = ", ".join(str(int(round(hands[n][axis] - feet))) for n in names)
        lines.append("static const signed char player_hand_%s[%d] = {%s};\n" % ("xy"[axis], len(names), values))
    lines.append("static const char* const dev_names[%d] = {%s};\n" % (
        len(dev_names), ", ".join('"%s"' % n for n in dev_names)))
    lines.append("\n#endif\n")
    with open(os.path.join(gen, "sprites.h"), "w") as f:
        f.write("".join(lines))


def write_scene(gen, name, grid, spots, walk, prefix="", grid_name="walk_grid", crowd=None):
    """gen/scene_<name>.{h,c,json}: the walk grid and spots. Every macro gets the prefix, so two rooms' headers
    can be included together; crowd (lists of screen points) adds the looping attendee paths."""
    guard = "SCENE_%s_H" % name.upper()
    h = [HEADER, "#ifndef %s\n#define %s\n\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n" % (guard, guard),
         "#define %sWALK_W %d\n#define %sWALK_H %d\n#define %sWALK_CELL %d\n" % (
             prefix, walk[0], prefix, walk[1], prefix, collision.CELL)]
    h += ["#define %s%s %d\n" % (prefix, k, v) for k, v in sorted(spots.items())]
    h.append("\nextern const unsigned char %s[%sWALK_W * %sWALK_H];\n" % (grid_name, prefix, prefix))
    c = [HEADER, "#include \"scene_%s.h\"\n\n" % name]
    if crowd:
        h.append("\n#define %sCROWD_N %d\n#define %sPATH_MAX 4\n" % (prefix, len(crowd), prefix))
        h.append("extern const unsigned char hall_crowd_len[%sCROWD_N];\n" % prefix)
        h.append("extern const short hall_crowd_path[%sCROWD_N][%sPATH_MAX][2];\n" % (prefix, prefix))
        c.append("const unsigned char hall_crowd_len[%sCROWD_N] = {%s};\n\n" % (
            prefix, ", ".join(str(len(p)) for p in crowd)))
        rows = []
        for path in crowd:
            pts = list(path) + [(0, 0)] * (4 - len(path))
            rows.append("{" + ", ".join("{%d, %d}" % (x, y) for x, y in pts) + "}")
        c.append("const short hall_crowd_path[%sCROWD_N][%sPATH_MAX][2] = {\n    %s\n};\n\n" % (
            prefix, prefix, ",\n    ".join(rows)))
    h.append("\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n")
    with open(os.path.join(gen, "scene_%s.h" % name), "w") as f:
        f.write("".join(h))
    rows = [", ".join(str(v) for v in grid[j * walk[0]:(j + 1) * walk[0]]) for j in range(walk[1])]
    c.append("const unsigned char %s[%sWALK_W * %sWALK_H] = {\n    %s\n};\n" % (
        grid_name, prefix, prefix, ",\n    ".join(rows)))
    with open(os.path.join(gen, "scene_%s.c" % name), "w") as f:
        f.write("".join(c))
    data = {"walk_w": walk[0], "walk_h": walk[1], "cell": collision.CELL, "spots": spots, "grid": grid}
    if crowd:
        data["crowd"] = [[list(pt) for pt in path] for path in crowd]
    with open(os.path.join(gen, "scene_%s.json" % name), "w") as f:
        json.dump(data, f)


def build_hall(hall_renders, graphics, gen, sprite_box, report):
    """The hall's grid (the stage reachable with the gate open, the orb with it shut), its crowd paths in screen
    pixels (each segment on the floor), and the attendee sprites."""
    hall = importlib.import_module("scenes.hall")
    with open(os.path.join(hall_renders, "footprints.json")) as f:
        fp = json.load(f)
    grid, spots, walk = collision.build(fp, sprite_box, hall.WALK_SPOTS)
    gx, gy = spots["GATE_X"], spots["GATE_Y"]
    hx, hy = collision.GATE_HALF
    shut = collision.feet_reach(grid, walk[0], walk[1], spots["START_X"], spots["START_Y"],
                                blocked=lambda x, y: abs(x - gx) <= hx and abs(y - gy) <= hy)
    if (spots["ORB_X"], spots["ORB_Y"]) not in shut:
        raise gba.ArtError("hall: the orb cannot be reached with the gate shut")
    if (spots["STAGE_X"], spots["STAGE_Y"]) in shut:
        raise gba.ArtError("hall: the stage can be reached around the rope")
    crowd = []
    for path in hall.CROWD:
        pts = [tuple(int(round(v)) for v in iso.project(fp["camera"], (x, y, 0))) for x, y in path]
        for x, y in collision.crowd_walk(pts, collision._tuning("CROWD_STEP")):     # the feet as the rules move them
            if not grid[(y // collision.CELL) * walk[0] + x // collision.CELL]:
                raise gba.ArtError("hall: a crowd path leaves the floor at (%d, %d)" % (x, y))
        crowd.append(pts)
    write_scene(gen, "hall", grid, spots, walk, prefix="HALL_", grid_name="hall_walk_grid", crowd=crowd)
    report["hall_walkable_cells"] = sum(grid)
    names = charspec.frame_names(charspec.CROWD_ANIMS, range(charspec.DIRS))
    for k in range(len(hall.ATTENDEES)):
        write_sprite(graphics, "crowd%d" % k,
                     [gba.shrink(load(os.path.join(hall_renders, "chars", "crowd%d" % k, n + ".png"))) for n in names])


def build(renders, scene_name, graphics, gen, out_dir=os.path.join(GAME, "out"), night_renders=None,
          dawn_renders=None, hall_renders=None):
    scene = importlib.import_module("scenes." + scene_name)
    os.makedirs(graphics, exist_ok=True)
    os.makedirs(gen, exist_ok=True)
    report = {}
    room = gba.shrink(load(os.path.join(renders, "room.png")))
    palette, px = gba.quantize_room(room)
    rooms = [("office_day", room, palette, px)]
    for label, where in (("night", night_renders), ("dawn", dawn_renders)):
        if where:                                      # without a variant render, the day room stands in
            other = gba.shrink(load(os.path.join(where, "room.png")))
            rooms.append(("office_" + label, other) + tuple(gba.quantize_room(other)))
        else:
            rooms.append(("office_" + label, room, palette, px))
    if hall_renders:
        hall_room = gba.shrink(load(os.path.join(hall_renders, "room.png")))
        rooms.append(("hall", hall_room) + tuple(gba.quantize_room(hall_room)))
    counts = write_rooms(gen, out_dir, rooms)
    report["room_tiles"], report["night_tiles"] = counts["office_day"], counts["office_night"]
    report["dawn_tiles"], report["hall_tiles"] = counts["office_dawn"], counts.get("hall", 0)
    palettes = {"office_day": "office_palette", "office_night": "office_night_palette",
                "office_dawn": "office_dawn_palette", "hall": "hall_palette"}
    for room_name, _, pal, _ in rooms:
        name = palettes[room_name]
        gba.write_bmp(os.path.join(graphics, name + ".bmp"), (16, 16), bytes(range(256)), pal)
        gba.write_json(os.path.join(graphics, name + ".json"), {"type": "bg_palette", "bpp_mode": "bpp_8"})
    report["colours"] = len(set(palette[1:240]))
    chars = os.path.join(renders, "chars")
    names = charspec.frame_names(charspec.PLAYER_ANIMS, range(charspec.DIRS))
    frames = [gba.shrink(load(os.path.join(chars, "player", n + ".png"))) for n in names]
    pal, pixels, size = gba.sprite_sheet(frames)
    fw, fh = charspec.PLAYER_FRAME
    top, bottom = split_frames(pixels, fw, fh, 64)
    write_sheet(graphics, "player_top", top, (fw, 64 * len(frames)), pal, 64)
    write_sheet(graphics, "player_bottom", bottom, (fw, (fh - 64) * len(frames)), pal, fh - 64)
    report["sprite_box"] = drawn_box(pixels, fw, fh, charspec.FEET)
    dev_names = charspec.frame_names(charspec.DEV_ANIMS, [0])
    dev_head = 0
    for k in range(len(scene.DEVS)):
        _, dev_px = write_sprite(graphics, "dev%d" % k,
                                 [gba.shrink(load(os.path.join(chars, "dev%d" % k, n + ".png"))) for n in dev_names])
        dev_head = max(dev_head, -drawn_box(dev_px, charspec.DEV_FRAME[0], charspec.DEV_FRAME[1], charspec.DEV_FEET)[1])
    with open(os.path.join(chars, "player", "hands.json")) as f:
        write_sprites_h(gen, names, json.load(f), scene.DEV_NAMES, -report["sprite_box"][1], dev_head)
    write_sprite(graphics, "icons", icons.icons(), palette=icons.UI_PALETTE)
    write_sprite(graphics, "pill", [icons.pill()], check_edges=False, palette=icons.UI_PALETTE)
    write_sprite(graphics, "meter", icons.meter(), palette=icons.UI_PALETTE)
    write_sprite(graphics, "hud_strip", [icons.hud_strip()], check_edges=False, palette=icons.UI_PALETTE)
    write_sprite(graphics, "hud_bar", icons.hud_bar(), check_edges=False, palette=icons.UI_PALETTE)
    write_sprite(graphics, "bug", icons.bug(), palette=icons.UI_PALETTE)
    write_sprite(graphics, "spark", icons.spark(), palette=icons.UI_PALETTE)
    write_sprite(graphics, "pizza", [icons.pizza()], palette=icons.UI_PALETTE)
    write_sprite(graphics, "rain", icons.rain(), check_edges=False, palette=icons.UI_PALETTE)
    write_sprite(graphics, "gate", [icons.gate()], check_edges=False, palette=icons.UI_PALETTE)
    write_sprite(graphics, "card", icons.card(), check_edges=False, palette=icons.UI_PALETTE)
    write_sprite(graphics, "confetti", icons.confetti(), palette=icons.UI_PALETTE)
    write_sprite(graphics, "flash", [icons.flash()], check_edges=False, palette=icons.UI_PALETTE)
    write_sprite(graphics, "spot", [icons.spot()], check_edges=False, palette=icons.UI_PALETTE)
    write_sprite(graphics, "grade", icons.grades(), palette=icons.UI_PALETTE)
    keyed = logo.load_keyed(logo.SOURCE)
    logo_pal, _ = write_sprite(graphics, "logo_title", logo_frames(logo.pixelate(keyed, 176), 64, 64, 3), check_edges=False)
    write_sprite(graphics, "logo_small", logo_frames(logo.pixelate(keyed, 88, 11), 64, 32, 2), check_edges=False,
                 palette=logo_pal)
    with open(os.path.join(renders, "footprints.json")) as f:
        grid, spots, walk = collision.build(json.load(f), report["sprite_box"], scene.WALK_SPOTS)
    write_scene(gen, scene.NAME, grid, spots, walk)
    report["walkable_cells"] = sum(grid)
    if hall_renders:
        build_hall(hall_renders, graphics, gen, report["sprite_box"], report)
    return report


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--renders", required=True)
    ap.add_argument("--scene", required=True)
    ap.add_argument("--graphics", required=True)
    ap.add_argument("--gen", required=True)
    ap.add_argument("--night-renders")
    ap.add_argument("--dawn-renders")
    ap.add_argument("--hall-renders")
    a = ap.parse_args()
    try:
        print(json.dumps(build(a.renders, a.scene, a.graphics, a.gen, night_renders=a.night_renders,
                               dawn_renders=a.dawn_renders, hall_renders=a.hall_renders)))
    except gba.ArtError as e:
        sys.exit("ART LIMIT: %s" % e)


if __name__ == "__main__":
    main()
