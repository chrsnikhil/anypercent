"""The rules' view of the circuit, from track_geom.py: rules/track_data.c and rules/track.h (surface map, centre line,
AI waypoints, the grid, boost pads). Run from the game directory:
    /opt/arca-sandbox/venv/bin/python tools/art/track_data.py
build_track.py (the art) imports surface_map() and PADS so the pictures sit on the same cells."""
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import track_geom as G  # noqa: E402

GAME = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SURF_ROAD, SURF_CURB, SURF_SLOW, SURF_WALL, SURF_BOOST = range(5)

# World-orb boost pads: (arc px from the line, lateral px: + right of travel). Each covers 2 x 2 cells.
PADS = [(80, -12), (1600, 10), (3950, -10)]
WAYPOINT_STEP = 160            # px of arc between AI waypoints (-> 34 for a 5.4 km lap)
GRID = [(-36, -14), (-36, 14), (-76, -14), (-76, 14)]    # (arc, lateral) of karts 1, 2, 3 and the player (0) last
GRID_ORDER = [1, 2, 3, 0]      # kart index on each grid slot: rivals in front, the player at the back


def tuning(name):
    """An integer #define from rules/tuning.h."""
    import re
    with open(os.path.join(GAME, "rules", "tuning.h")) as f:
        return int(re.search(r"^#define %s\s+\(?(-?(?:0x[0-9a-fA-F]+|\d+))" % name, f.read(), re.M).group(1), 0)


TOP = tuning("TOP_ROAD")       # player road top speed
STEER_RATE = tuning("STEER")   # heading steps per frame at speed


def at_arc(points, arc, lateral=0.0):
    """(x, y, heading) at `arc` px along the centre line (wraps), shifted `lateral` px to the right of travel."""
    n = len(points)
    f = (arc / G.POINT_STEP) % n
    i = int(f)
    t = f - i
    p = points[i] * (1 - t) + points[(i + 1) % n] * t
    d = points[(i + 1) % n] - points[i]
    d = d / math.hypot(*d)
    right = np.array([-d[1], d[0]])
    p = p + right * lateral
    return float(p[0]), float(p[1]), int(round(math.atan2(d[1], d[0]) / (2 * math.pi) * 1024)) % 1024


def surface_map(points):
    """128 x 128 uint8 SURF_* per cell (cell centre distance to the centre line), with the boost pads stamped."""
    idx, dist, _ = G.nearest(points, G.cell_centres())
    cells = G.classify(dist).reshape(G.CELLS, G.CELLS)
    for arc, lat in PADS:
        x, y, _ = at_arc(points, arc, lat)
        cx, cy = int(round(x / G.CELL)), int(round(y / G.CELL))
        for yy in (cy - 1, cy):
            for xx in (cx - 1, cx):
                assert cells[yy, xx] == SURF_ROAD, "boost pad off the road at arc %d" % arc
                cells[yy, xx] = SURF_BOOST
    return cells


def waypoints(points):
    """AI waypoints: every WAYPOINT_STEP px, pulled toward the inside of the corner, with a target speed from the
    tightest radius in the next stretch (the speed at which the kart's steering rate follows the curve)."""
    n = len(points)
    radius = G.radii(points, 4)
    tang = np.roll(points, -2, 0) - np.roll(points, 2, 0)
    tang /= np.hypot(tang[:, 0], tang[:, 1])[:, None]
    # signed curvature: + turning right (clockwise on screen)
    a, b = np.roll(points, 4, 0), np.roll(points, -4, 0)
    t1, t2 = points - a, b - points
    turn = np.sign(t1[:, 0] * t2[:, 1] - t1[:, 1] * t2[:, 0])
    omega = STEER_RATE * 2 * math.pi / 1024
    out = []
    step = WAYPOINT_STEP // G.POINT_STEP
    for k in range(0, n - step // 2, step):
        right = np.array([-tang[k, 1], tang[k, 0]])
        r = radius[k]
        pull = min(16.0, 16.0 * 90.0 / r) if r < 400 else 0.0
        p = points[k] + right * pull * turn[k]
        ahead = [radius[(k + j) % n] for j in range(0, step + 6)]
        v = min(TOP / 65536.0, 0.9 * omega * min(ahead))
        out.append((int(round(p[0])), int(round(p[1])), int(round(v * 65536))))
    return out


def write(points, total):
    cells = surface_map(points)
    wps = waypoints(points)
    grid = []
    for (arc, lat), kart in zip(GRID, GRID_ORDER):
        x, y, h = at_arc(points, total + arc, lat)
        grid.append((kart, int(round(x)), int(round(y)), h))
    grid.sort()
    n = len(points)
    lines = ["/* Generated by tools/art/track_data.py from tools/art/track_geom.py. Do not edit. */",
             '#include "track.h"', "",
             "const uint8_t md_cells[TRACK_CELLS * TRACK_CELLS] = {"]
    flat = cells.ravel()
    for r in range(0, len(flat), 64):
        lines.append("    " + ",".join(str(int(v)) for v in flat[r:r + 64]) + ",")
    lines.append("};")
    lines.append("const int16_t md_points[TRACK_POINTS][2] = {")
    for r in range(0, n, 8):
        lines.append("    " + ",".join("{%d,%d}" % (round(x), round(y)) for x, y in points[r:r + 8]) + ",")
    lines.append("};")
    lines.append("const int32_t md_waypoints[TRACK_WAYPOINTS][3] = {")
    for x, y, v in wps:
        lines.append("    {%d, %d, 0x%08X}," % (x, y, v))
    lines.append("};")
    lines.append("const int32_t md_track_points = TRACK_POINTS;    /* for the tests (ctypes) */")
    lines.append("const int16_t md_grid[N_KARTS][3] = {")
    for kart, x, y, h in grid:
        lines.append("    {%d, %d, %d},    /* kart %d */" % (x, y, h, kart))
    lines.append("};")
    with open(os.path.join(GAME, "rules", "track_data.c"), "w") as f:
        f.write("\n".join(lines) + "\n")
    # the lap length the rules use: whole points (every POINT_STEP px, the last spacing absorbs the rest)
    header = """/* The circuit, generated by tools/art/track_data.py (do not edit): the surface map (one SURF_* per 8 x 8 px cell of
   the 1024 x 1024 px plane), the centre line (a point every TRACK_POINT_STEP px from the start/finish line, in lap
   order), the AI waypoints (x, y, target speed Q16.16) and the grid (x, y, heading per kart). */
#ifndef TRACK_H
#define TRACK_H
#include <stdint.h>

#define TRACK_CELLS       %d
#define TRACK_CELL        %d
#define TRACK_POINTS      %d
#define TRACK_POINT_STEP  %d
#define TRACK_LEN         %d       /* TRACK_POINTS * TRACK_POINT_STEP: arc positions are point index * step */
#define TRACK_SECTORS     %d
#define TRACK_WAYPOINTS   %d
#define TRACK_PADS        %d
#ifndef N_KARTS
#define N_KARTS 4
#endif

extern const uint8_t md_cells[TRACK_CELLS * TRACK_CELLS];
extern const int16_t md_points[TRACK_POINTS][2];
extern const int32_t md_waypoints[TRACK_WAYPOINTS][3];
extern const int16_t md_grid[N_KARTS][3];
extern const int32_t md_track_points;

#endif
""" % (G.CELLS, G.CELL, n, G.POINT_STEP, n * G.POINT_STEP, G.SECTORS, len(wps), len(PADS))
    with open(os.path.join(GAME, "rules", "track.h"), "w") as f:
        f.write(header)
    return cells, wps, grid


if __name__ == "__main__":
    pts, total = G.centre_line()
    problems = G.check(pts, total)
    assert not problems, problems
    cells, wps, grid = write(pts, total)
    print("track: %d points (%d px), %d waypoints, surfaces %s" % (
        len(pts), len(pts) * G.POINT_STEP, len(wps), np.bincount(cells.ravel(), minlength=5).tolist()))
