"""level/map.txt -> gen/map.c + gen/map.h (the level the rules parse at init). Validates the map first: size,
closed border, the counts the plan asks for (one start, 10-15 bugs, 4 Arkiv shelves, one keycard reader, one exit
terminal, a pushable wall and a secret room), doors set between two walls, and every walkable cell reachable from
the start with doors and the pushable wall opened.
    python tools/level/build_level.py [--check]      (--check: validate only)"""
import os
import sys
from collections import deque

GAME = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
W = H = 48
WALLS = set("#cowAKXP")
WALK = set(".sb@")
KNOWN = WALLS | WALK | {"D", "L"}


def load(path=os.path.join(GAME, "level", "map.txt")):
    lines = [ln.rstrip("\n") for ln in open(path) if ln.strip() and not ln.startswith(";")]
    angle = int(lines[0])
    rows = lines[1:]
    return angle, rows


def validate(angle, rows):
    errs = []
    if not 0 <= angle < 1024:
        errs.append("start angle %d out of 0..1023" % angle)
    if len(rows) != H or any(len(r) != W for r in rows):
        return errs + ["the map must be %d rows of %d cells" % (H, W)]
    cells = "".join(rows)
    for i, ch in enumerate(cells):
        if ch not in KNOWN:
            errs.append("unknown cell %r at (%d, %d)" % (ch, i % W, i // W))
    for x in range(W):
        for y in (0, H - 1):
            if rows[y][x] not in WALLS:
                errs.append("open border at (%d, %d)" % (x, y))
    for y in range(H):
        for x in (0, W - 1):
            if rows[y][x] not in WALLS:
                errs.append("open border at (%d, %d)" % (x, y))
    count = {ch: cells.count(ch) for ch in KNOWN}
    if count["@"] != 1:
        errs.append("%d starts (want 1)" % count["@"])
    if not 18 <= count["b"] <= 25:
        errs.append("%d bugs (want 18-25)" % count["b"])
    if not 4 <= count["A"] <= 6:
        errs.append("%d Arkiv shelves (want 4-6)" % count["A"])
    for ch, want in (("K", 1), ("X", 1), ("L", 1)):
        if count[ch] != want:
            errs.append("%d %r cells (want %d)" % (count[ch], ch, want))
    if count["P"] < 1 or count["s"] < 1:
        errs.append("no secret room (a P wall and s floor)")
    if count["D"] + count["L"] + count["P"] > 24:
        errs.append("%d sliding cells (the rules hold 24)" % (count["D"] + count["L"] + count["P"]))
    for y in range(1, H - 1):
        for x in range(1, W - 1):
            if rows[y][x] in "DL":
                ew = rows[y][x - 1] in WALLS and rows[y][x + 1] in WALLS
                ns = rows[y - 1][x] in WALLS and rows[y + 1][x] in WALLS
                if not (ew or ns):
                    errs.append("door at (%d, %d) is not set between two walls" % (x, y))
    if errs:
        return errs
    start = cells.index("@")
    seen, todo = {start}, deque([start])
    while todo:
        i = todo.popleft()
        x, y = i % W, i // W
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            j = (y + dy) * W + x + dx
            if j not in seen and (cells[j] in WALK or cells[j] in "DLP"):
                seen.add(j)
                todo.append(j)
    for i, ch in enumerate(cells):
        if ch in WALK and i not in seen:
            errs.append("(%d, %d) is walkable but cannot be reached from the start" % (i % W, i // W))
    # the keycard must be reachable without passing the locked door, and the exit only through it
    reach, todo = {start}, deque([start])
    while todo:
        i = todo.popleft()
        x, y = i % W, i // W
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            j = (y + dy) * W + x + dx
            if j not in reach and (cells[j] in WALK or cells[j] in "DP"):
                reach.add(j)
                todo.append(j)
    def next_to(ch):
        i = cells.index(ch)
        return any(n in reach for n in (i - 1, i + 1, i - W, i + W))
    if not next_to("K"):
        errs.append("the keycard reader is behind the locked door")
    if next_to("X"):
        errs.append("the exit terminal can be reached without the keycard")
    return errs


def emit(angle, rows):
    cells = "".join(rows)
    os.makedirs(os.path.join(GAME, "gen"), exist_ok=True)
    with open(os.path.join(GAME, "gen", "map.h"), "w", newline="\n") as f:
        f.write("/* Generated by tools/level/build_level.py from level/map.txt; do not edit. */\n"
                "#ifndef SEGF_MAP_H\n#define SEGF_MAP_H\n#include <stdint.h>\n\n"
                "extern const uint16_t LEVEL_ANGLE;          /* the player's start angle */\n"
                "extern const char LEVEL_ROWS[%d];         /* %d rows of %d cells, the map.txt legend */\n\n"
                "#endif\n" % (W * H + 1, H, W))
    with open(os.path.join(GAME, "gen", "map.c"), "w", newline="\n") as f:
        f.write("/* Generated by tools/level/build_level.py from level/map.txt; do not edit. */\n"
                "#include \"map.h\"\n\nconst uint16_t LEVEL_ANGLE = %d;\n\nconst char LEVEL_ROWS[%d] =\n" % (angle, W * H + 1))
        f.write("\n".join('    "%s"' % r for r in rows) + ";\n")


def main():
    angle, rows = load()
    errs = validate(angle, rows)
    if errs:
        sys.exit("level/map.txt:\n  " + "\n  ".join(errs))
    if "--check" not in sys.argv:
        emit(angle, rows)
    print("level ok: %d bugs" % "".join(rows).count("b"))


if __name__ == "__main__":
    main()
