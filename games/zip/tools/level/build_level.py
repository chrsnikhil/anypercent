"""Builds ZIP's level from level/level.txt:
    gen/zip_tiles.c   the tile table (masks, angles, glyphs) and the loop path, for the rules
    gen/level.c/.h    the tile grid and the things, for the rules (and the view)
    graphics/level.bmp/.json   the level background (big regular BG), drawn by tools/art/level_art.py
Run from the game directory: python tools/level/build_level.py [--no-bg]

level.txt: lines starting with ';' are comments (the legend); the rest is the grid, all rows the same width.
Terrain glyphs are in tiles.py; things: o packet, S yellow spring, R red spring, > booster, e bug, x spikes,
C checkpoint, F finish line, P start, L loop (its bottom centre; the floor is the row below). Decor (drawn only):
r rack, l lamp, n sign, K laptop, D demo-day screen. A thing or decor glyph is an empty tile for the rules."""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import tiles as TL  # noqa: E402

GEN = os.path.join(GAME, "gen")
LEVEL_TXT = os.path.join(GAME, "level", "level.txt")

THINGS = {"o": 0, "S": 1, "R": 2, ">": 3, "e": 4, "x": 5, "C": 6, "F": 7, "L": 8}
DECOR = set("rlnKD")
BODY_H = 10
LOOP_RS = 64                   # the loop's inner surface radius (px)
LOOP_RC = LOOP_RS - BODY_H     # the player's centre path radius
LOOP_STEP = 4                  # px of arc between path points (LOOP_STEP_PX in tuning.h)
BUG_RANGE = 2                  # a bug patrols +- this many tiles (>= 1: the rules divide by the span)
MAX_ENTS = 512                 # rules/zip_world.c MAX_ENTS


class LevelError(Exception):
    pass


def read_level(path=LEVEL_TXT):
    with open(path) as f:
        rows = [ln.rstrip("\n") for ln in f if not ln.startswith(";") and ln.strip("\n")]
    w = len(rows[0])
    for i, r in enumerate(rows):
        if len(r) != w:
            raise LevelError("row %d is %d wide, not %d" % (i, len(r), w))
    return rows


def parse(rows):
    """(tile id grid, styles, things [(x, y, kind, arg)], start (x, y), decor [(glyph, col, row)])."""
    h, w = len(rows), len(rows[0])
    grid = [[0] * w for _ in range(h)]
    styles = [["plain"] * w for _ in range(h)]
    things, decor, start = [], [], None
    for r, line in enumerate(rows):
        for c, ch in enumerate(line):
            if ch in TL.GLYPH_TO_ID:
                grid[r][c] = TL.GLYPH_TO_ID[ch]
                if ch == "H":
                    styles[r][c] = "switch"
            elif ch in THINGS:
                k = THINGS[ch]
                if k == 0:
                    things.append((c * 16 + 8, r * 16 + 8, k, 0))
                elif k == 7:
                    things.append((c * 16, r * 16 + 16, k, 0))
                elif k == 8:
                    things.append((c * 16 + 8, r * 16 + 16, k, 0))
                else:
                    things.append((c * 16 + 8, r * 16 + 16, k, BUG_RANGE if k == 4 else 0))
            elif ch == "P":
                start = (c * 16 + 8, r * 16 + 16 - BODY_H)
            elif ch in DECOR:
                decor.append((ch, c, r))
            elif ch != " ":
                raise LevelError("unknown glyph %r at column %d row %d" % (ch, c, r))
    if start is None:
        raise LevelError("no start (P)")
    if len(things) > MAX_ENTS:
        raise LevelError("%d things: the rules hold state for at most %d (MAX_ENTS in rules/zip_world.c)"
                         % (len(things), MAX_ENTS))
    for x, y, k, a in things:
        if k == THINGS["e"] and a < 1:
            raise LevelError("the bug at x=%d has patrol range %d: it must be >= 1 tile" % (x, a))
    things.sort(key=lambda t: (t[0], t[1], t[2]))
    return grid, styles, things, start, decor


def loop_path():
    """The loop's centre path from its entry (the bottom point, (0, 0)), counter-clockwise on screen (right, up, over,
    down), as integer offsets, with the travel angle (0-255, rising to the right positive) at each point."""
    n = round(2 * math.pi * LOOP_RC / LOOP_STEP)
    pts, angs = [], []
    for i in range(n + 1):
        th = 2 * math.pi * i / n
        pts.append((round(LOOP_RC * math.sin(th)), round(LOOP_RC * math.cos(th)) - LOOP_RC))
        angs.append(round(th * 256 / (2 * math.pi)) & 255)
    return pts, angs


def write_tiles_c():
    pts, angs = loop_path()
    out = ["/* Generated by tools/level/build_level.py from tools/level/tiles.py: do not edit. */",
           "#include \"zip_level.h\"", ""]
    out.append("const uint8_t ZIP_TILE_COUNT = %d;" % len(TL.TYPES))
    out.append("const uint8_t ZIP_TILE_MASK[][16] = {")
    for g, name, m, a in TL.TYPES:
        out.append("    {%s},   /* %s */" % (", ".join(str(v) for v in m), name))
    out.append("};")
    out.append("const uint8_t ZIP_TILE_ANGLE[] = {%s};" % ", ".join(str(t[3]) for t in TL.TYPES))
    glyphs = "".join(t[0] for t in TL.TYPES).replace("\\", "\\\\")
    out.append("const char ZIP_TILE_GLYPHS[] = \"%s\";" % glyphs)
    out.append("")
    out.append("/* the loop: radius %d centre path, a point every %d px of arc */" % (LOOP_RC, LOOP_STEP))
    out.append("const uint16_t ZIP_LOOP_POINTS = %d;" % len(pts))
    out.append("const int16_t ZIP_LOOP_PATH[][2] = {")
    for i in range(0, len(pts), 8):
        out.append("    " + " ".join("{%d, %d}," % p for p in pts[i:i + 8]))
    out.append("};")
    out.append("const uint8_t ZIP_LOOP_ANGLE[] = {")
    for i in range(0, len(angs), 16):
        out.append("    " + " ".join("%d," % a for a in angs[i:i + 16]))
    out.append("};")
    with open(os.path.join(GEN, "zip_tiles.c"), "w") as f:
        f.write("\n".join(out) + "\n")


def write_level_c(grid, things, start):
    h, w = len(grid), len(grid[0])
    out = ["/* Generated by tools/level/build_level.py from level/level.txt: do not edit. */",
           "#include \"level.h\"", ""]
    out.append("static const uint8_t TILES[%d] = {" % (w * h))
    for r in range(h):
        out.append("    " + ",".join(str(v) for v in grid[r]) + ",")
    out.append("};")
    out.append("static const zip_ent ENTS[%d] = {" % max(1, len(things)))
    for x, y, k, a in things:
        out.append("    {%d, %d, %d, %d}," % (x, y, k, a))
    if not things:
        out.append("    {0, 0, 0, 0},")
    out.append("};")
    out.append("const zip_level ZIP_LEVEL = {%d, %d, TILES, %d, ENTS, %d, %d};" % (w, h, len(things), start[0], start[1]))
    with open(os.path.join(GEN, "level.c"), "w") as f:
        f.write("\n".join(out) + "\n")
    hdr = ["/* Generated by tools/level/build_level.py: do not edit. */", "#ifndef ZIP_GEN_LEVEL_H",
           "#define ZIP_GEN_LEVEL_H", "#include \"zip_level.h\"",
           "#define LEVEL_W %d" % w, "#define LEVEL_H %d" % h, "#define LEVEL_PACKETS %d" % sum(1 for t in things if t[2] == 0),
           "#endif"]
    with open(os.path.join(GEN, "level.h"), "w") as f:
        f.write("\n".join(hdr) + "\n")


def main(argv):
    os.makedirs(GEN, exist_ok=True)
    rows = read_level()
    grid, styles, things, start, decor = parse(rows)
    write_tiles_c()
    write_level_c(grid, things, start)
    if "--no-bg" not in argv:
        import render_level
        render_level.build(grid, styles, things, decor)
    print("level %dx%d tiles, %d things (%d packets)" % (len(grid[0]), len(grid), len(things),
                                                        sum(1 for t in things if t[2] == 0)))


if __name__ == "__main__":
    main(sys.argv[1:])
