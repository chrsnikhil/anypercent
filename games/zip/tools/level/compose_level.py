"""Composes ZIP's level into level/level.txt (the level's source of truth is that text grid; this script is how it
was laid out, section by section, so slopes always join up). Run from the game directory:
    python tools/level/compose_level.py
Glyphs: see tools/level/build_level.py. Bot hints are written as '; bot <action> <column>' comment lines."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(GAME, "level", "level.txt")

W, H, BASE = 1024, 32, 26          # W: room to compose in; the level is trimmed to a multiple of 16 columns

LEGEND = """; ZIP -- the venue network, 32 tiles of 16 px tall. Generated by tools/level/compose_level.py.
; terrain: . empty  # solid  H switch block (solid)  / \\ 45-degree rise/fall  ab rise 22.5 (two tiles)  cd fall 22.5
; things:  o packet  S yellow spring  R red spring  > booster (World orb)  e bug  x spikes  C checkpoint (Arkiv rack)
;          F finish line (Chainlink)  P start  L loop (bottom centre, on the floor)
; decor:   r server rack  l warning lamp  n sign  K laptop  D demo-day screen
; sections: laptop start | switch farm | checkpoint | the hill and the loop | booster straight | server climb | finish
"""


class Level:
    def __init__(self):
        self.g = [["."] * W for _ in range(H)]
        self.c = 0
        self.gr = BASE                              # the ground row: first solid row of flat ground here
        self.hints = []
        self.pending = []

    # -- terrain, left to right from the cursor --
    def _fill(self, col, row, glyph="#"):
        for r in range(row, H):
            self.g[r][col] = glyph

    def flat(self, n, glyph="#"):
        for _ in range(n):
            self._fill(self.c, self.gr, glyph)
            self.c += 1
        return self

    def up45(self, n):
        for _ in range(n):
            self.gr -= 1
            self.g[self.gr][self.c] = "/"
            self._fill(self.c, self.gr + 1)
            self.c += 1
        return self

    def down45(self, n):
        for _ in range(n):
            self.g[self.gr][self.c] = "\\"
            self._fill(self.c, self.gr + 1)
            self.gr += 1
            self.c += 1
        return self

    def up22(self, n):
        for _ in range(n):
            self.gr -= 1
            self.g[self.gr][self.c] = "a"
            self.g[self.gr][self.c + 1] = "b"
            self._fill(self.c, self.gr + 1)
            self._fill(self.c + 1, self.gr + 1)
            self.c += 2
        return self

    def down22(self, n):
        for _ in range(n):
            self.g[self.gr][self.c] = "c"
            self.g[self.gr][self.c + 1] = "d"
            self._fill(self.c, self.gr + 1)
            self._fill(self.c + 1, self.gr + 1)
            self.gr += 1
            self.c += 2
        return self

    def pit(self, n):
        self.c += n
        return self

    def rise(self, k):
        """A vertical step up of k tiles (a wall to jump or spring over)."""
        self.gr -= k
        return self

    def drop(self, k):
        self.gr += k
        return self

    # -- things --
    def put(self, col, row, glyph):
        assert self.g[row][col] == ".", (col, row, glyph, self.g[row][col])
        self.g[row][col] = glyph
        return self

    def on_floor(self, col, glyph):
        """A thing standing on the ground at column col (the top of the solid run from the level's bottom)."""
        r = H - 1
        while r >= 0 and self.g[r][col] in "#H":
            r -= 1
        if r == H - 1:
            raise AssertionError("no floor at %d" % col)
        return self.put(col, r, glyph)

    def ground_row(self, col):
        """The row of the ground's surface tile at col (bottom-up: floating blocks above do not count)."""
        r = H - 1
        while r >= 0 and self.g[r][col] in "#H":
            r -= 1
        if r >= 0 and self.g[r][col] in "/\\abcd":
            return r
        assert r < H - 1, "no ground at %d" % col
        return r + 1

    def packets(self, c0, n, row=None, step=1, above=2):
        self.pending.append(("packets", (c0, n, row, step, above)))
        return self

    def arc(self, c0, n, top=4, above=2):
        self.pending.append(("arc", (c0, n, top, above)))
        return self

    def finish(self):
        """Places the packets (deferred, so a line may run past the terrain built when it was asked for)."""
        for kind, args in self.pending:
            (self._packets if kind == "packets" else self._arc)(*args)
        self.pending = []

    def _packets(self, c0, n, row=None, step=1, above=2):
        for i in range(n):
            col = c0 + i * step
            r = row if row is not None else self.ground_row(col) - above
            self.put(col, r, "o")
        return self

    def _arc(self, c0, n, top=4, above=2):
        """Packets in an arc over n columns, `top` tiles higher in the middle."""
        for i in range(n):
            t = i / max(1, n - 1)
            lift = round(top * 4 * t * (1 - t))
            col = c0 + i
            self.put(col, self.ground_row(col) - above - lift, "o")
        return self

    def block(self, col, row, w, h=1, glyph="H"):
        for r in range(row, row + h):
            for c in range(col, col + w):
                self.g[r][c] = glyph
        return self

    def hint(self, action, col):
        self.hints.append((action, col))
        return self

    def text(self):
        out = [LEGEND]
        for a, col in self.hints:
            out.append("; bot %s %d\n" % (a, col))
        out += ["".join(r[:self.width]) + "\n" for r in self.g]
        return "".join(out)


def compose():
    L = Level()
    # ---- A. laptop start (tutorial slopes) ------------------------------------------------------------------------
    L.flat(16)
    L.on_floor(0, "K")
    L.on_floor(9, "P")
    L.on_floor(14, "n")
    L.flat(12)
    L.packets(18, 6)
    L.up22(3)
    c = L.c
    L.flat(8)
    L.packets(c + 1, 6)
    L.down22(3)
    c = L.c
    L.flat(14)
    L.on_floor(c + 8, "e")
    L.arc(c + 5, 7, top=3)
    L.on_floor(c + 1, "r")
    L.up45(3)
    c = L.c
    L.flat(5)
    L.packets(c, 5)
    L.drop(3)                                               # a dip to hop out of
    L.flat(3)
    L.rise(3)
    c = L.c
    L.flat(5)
    L.packets(c + 1, 3)
    L.down45(3)
    c = L.c
    L.flat(12)
    L.on_floor(c + 2, "l")
    L.on_floor(c + 4, "r")
    L.on_floor(c + 5, "r")
    L.packets(c + 7, 4)
    L.up22(2)
    L.flat(4)
    L.down22(2)
    # ---- B. switch farm (springs, packets) -----------------------------------------------------------------------
    c = L.c
    L.flat(8)
    L.on_floor(c + 5, "S")                                  # up to a switch-top packet run
    L.block(c + 12, BASE - 9, 14, 1)
    L.packets(c + 13, 12, row=BASE - 10)
    L.flat(22)
    L.on_floor(c + 16, "e")
    L.on_floor(c + 24, "e")
    c = L.c
    L.rise(3)
    L.flat(10, "H")
    L.packets(c + 2, 6)
    L.drop(3)
    c = L.c
    L.flat(6)
    L.on_floor(c + 3, "x")
    L.on_floor(c + 4, "x")
    L.arc(c, 6, top=4)
    L.flat(6)
    c = L.c
    L.rise(4)
    L.flat(3, "H")
    L.rise(3)
    L.flat(8, "H")
    L.packets(c + 4, 6)
    c0 = L.c
    L.drop(7)
    L.flat(10)
    L.on_floor(c0 + 3, "R")                                 # a red spring: a high column of packets
    for k in range(6):
        L.put(c0 + 3, BASE - 6 - k * 2, "o")
    L.on_floor(c0 + 8, "r")
    c = L.c
    L.flat(10)
    L.on_floor(c + 3, "e")
    L.on_floor(c + 7, "x")
    L.on_floor(c + 8, "x")
    L.on_floor(c + 9, "x")
    L.arc(c + 5, 7, top=4)
    L.flat(8)
    c = L.c
    L.up45(2)
    L.flat(6, "H")
    L.packets(c + 2, 5)
    L.down45(2)
    L.flat(8)
    # ---- C. checkpoint -------------------------------------------------------------------------------------------
    c = L.c
    L.flat(10)
    L.on_floor(c + 4, "C")
    L.on_floor(c + 7, "r")
    L.on_floor(c + 8, "r")
    # ---- D. the hill and the loop ---------------------------------------------------------------------------------
    c = L.c
    L.up22(8)
    L.packets(c + 2, 5, step=3)
    c = L.c
    L.flat(10)
    L.packets(c + 1, 8)
    L.hint("roll", L.c - 1)                                 # the bot rolls down the hill into the loop
    L.down45(8)
    c = L.c
    L.flat(22)
    L.on_floor(c + 8, "L")
    L.on_floor(c + 18, "l")
    L.packets(c + 15, 6)
    # ---- E. the booster straight --------------------------------------------------------------------------------------
    c = L.c
    L.flat(10)
    L.on_floor(c + 3, ">")
    L.packets(c + 5, 5)
    for _ in range(3):
        c = L.c
        L.up22(2)
        L.flat(3)
        L.packets(c + 4, 3)
        L.down22(2)
        L.flat(4)
    c = L.c
    L.flat(12)
    L.on_floor(c + 3, "e")
    L.on_floor(c + 8, "e")
    L.arc(c + 1, 10, top=3)
    c = L.c
    L.down45(4)
    c = L.c
    L.flat(24)
    L.packets(c + 2, 16)
    L.on_floor(c + 20, ">")
    L.up45(4)
    c = L.c
    L.flat(14)
    L.on_floor(c + 5, "x")
    L.on_floor(c + 6, "x")
    L.on_floor(c + 3, "S")
    L.packets(c + 6, 5, row=BASE - 9)
    L.on_floor(c + 10, "r")
    c = L.c
    L.flat(12)
    L.on_floor(c + 2, ">")
    L.packets(c + 4, 8)
    L.up22(3)
    L.flat(6)
    L.down22(3)
    c = L.c
    L.flat(14)
    L.on_floor(c + 4, "e")
    L.on_floor(c + 10, "e")
    L.on_floor(c + 1, "l")
    # a spike bed with a spring over it
    c = L.c
    L.flat(12)
    L.on_floor(c + 1, "S")
    for k in range(3, 11):
        L.on_floor(c + k, "x")
    L.packets(c + 4, 6, row=BASE - 12)
    c = L.c
    L.flat(10)
    L.packets(c + 1, 6)
    # ---- F. the server climb -------------------------------------------------------------------------------------------
    for k in range(3):
        c = L.c
        L.flat(4)
        L.on_floor(c + 1, "S")
        L.on_floor(c + 3, "r")
        L.rise(5)
        c = L.c
        L.flat(10, "H")
        L.packets(c + 2, 6)
        if k == 1:
            L.on_floor(c + 6, "e")
    c = L.c
    L.flat(6, "H")
    L.hint("jump", c + 3)
    top = L.gr
    L.drop(BASE - top)                                     # a wide gap: jump it at speed, or fall to the floor
    c = L.c
    L.flat(12)
    L.on_floor(c + 11, "R")                                # ... and a red spring against the far wall
    L.on_floor(c + 3, "r")
    L.rise(BASE - top)
    c = L.c
    L.flat(8, "H")
    L.packets(c + 1, 5)
    L.down45(5)
    L.down22(5)
    c = L.c
    L.flat(12)
    L.on_floor(c + 4, ">")
    L.packets(c + 6, 6)
    L.up22(2)
    L.flat(4)
    L.down22(2)
    c = L.c
    L.flat(16)
    L.on_floor(c + 3, "e")
    L.on_floor(c + 8, "e")
    L.on_floor(c + 13, "e")
    L.arc(c + 2, 12, top=4)
    c = L.c
    L.up45(3)
    L.flat(8)
    L.packets(c + 4, 6)
    L.down45(3)
    c = L.c
    L.flat(10)
    L.on_floor(c + 3, "x")
    L.on_floor(c + 4, "x")
    L.on_floor(c + 5, "x")
    L.on_floor(c + 6, "x")
    L.on_floor(c + 1, "S")
    L.packets(c + 3, 5, row=L.gr - 10)
    L.flat(6)
    # ---- H. the cable ducts: 45-degree valleys and rolling hills ------------------------------------------------------
    c = L.c
    L.flat(6)
    L.on_floor(c + 2, "l")
    for k in range(6):
        c = L.c
        L.down45(4)
        c2 = L.c
        L.flat(3)
        L.packets(c2, 3)
        L.up45(4)
        L.flat(3)
        if k % 2:
            L.packets(L.c - 3, 3)
    c = L.c
    L.flat(10)
    L.on_floor(c + 5, "e")
    L.arc(c + 2, 7, top=3)
    for k in range(4):
        c = L.c
        L.up22(3)
        L.flat(2)
        L.packets(c + 6, 2)
        L.down22(3)
        L.flat(4)
        if k == 1:
            L.on_floor(L.c - 2, "r")
    # ---- I. the spring stairs -----------------------------------------------------------------------------------------
    c = L.c
    L.flat(8)
    L.on_floor(c + 3, "e")
    for k in range(3):
        c = L.c
        L.flat(4, "H" if k else "#")
        L.on_floor(c + 1, "S")
        L.rise(4)
        c = L.c
        L.flat(8, "H")
        L.packets(c + 2, 5)
        if k == 2:
            L.on_floor(c + 5, "e")
    c = L.c
    L.flat(4, "H")
    L.down22(6)
    L.packets(c + 6, 6, step=2)
    c = L.c
    L.flat(10)
    L.on_floor(c + 2, "r")
    L.on_floor(c + 3, "r")
    L.on_floor(c + 6, "e")
    # ---- J. the last stretch: bug pairs, spikes, springs ------------------------------------------------------------------
    c = L.c
    L.flat(14)
    L.on_floor(c + 3, "e")
    L.on_floor(c + 9, "e")
    L.arc(c + 1, 12, top=4)
    c = L.c
    L.flat(12)
    L.on_floor(c + 1, "S")
    for k in range(3, 10):
        L.on_floor(c + k, "x")
    L.packets(c + 4, 5, row=L.gr - 11)
    c = L.c
    L.up45(3)
    L.flat(6, "H")
    L.packets(c + 4, 5)
    L.down45(3)
    L.flat(8)
    # ---- K. the approach: a last climb and the run-in -----------------------------------------------------------------
    c = L.c
    L.flat(6)
    L.on_floor(c + 3, "e")
    L.up22(4)
    c = L.c
    L.flat(6, "H")
    L.packets(c + 1, 4)
    L.rise(3)
    c = L.c
    L.flat(10, "H")
    L.packets(c + 2, 6)
    L.on_floor(c + 6, "e")
    L.down45(3)
    L.down22(4)
    c = L.c
    L.flat(10)
    L.arc(c + 1, 8, top=3)
    L.on_floor(c + 7, "l")
    # ---- G. the finish: the demo-day screen ---------------------------------------------------------------------------
    c = L.c
    L.flat(48)
    L.flat(-L.c % 16)
    L.packets(c + 2, 10)
    L.on_floor(c + 14, "F")
    L.on_floor(c + 17, "r")
    L.on_floor(c + 18, "r")
    L.on_floor(c + 24, "D")
    L.on_floor(c + 34, "r")
    L.on_floor(c + 35, "l")
    L.width = L.c
    L.finish()
    return L


def main():
    L = compose()
    with open(OUT, "w") as f:
        f.write(L.text())
    n = sum(r.count("o") for r in L.g)
    print("wrote %s: %d x %d, %d packets" % (OUT, L.width, H, n))


if __name__ == "__main__":
    main()
