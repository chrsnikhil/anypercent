"""
Modify a game: a git-tracked working copy you edit, rebuild and play.

  run.sh mod.py <id> init      working copy in games/work/<id> (source + sandbox fixes + saved patch)
  run.sh mod.py <id> build     rebuild it with the exact toolchain and command that built it
  run.sh mod.py <id> play      open the ROM in mGBA (a window on the Windows desktop, via WSLg)
  run.sh mod.py <id> diff      what you changed, relative to the untouched source
                               (new files count once you `git add` them in the working copy)
  run.sh mod.py <id> patch     save your changes to sandbox/patches/<id>.patch, so
                               05_build_games.py and every future build apply them
  run.sh mod.py <id> reset     throw the working copy away
  run.sh mod.py list           games you can build, with their toolchain

Your edits live in games/work/<id>, which 05_build_games.py never touches.
From Windows: \\\\wsl.localhost\\Ubuntu-24.04\\opt\\arca-sandbox\\games\\work\\<id>
"""
import glob
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("build_games", os.path.join(HERE, "05_build_games.py"))
bg = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bg)

G = bg.G
GIT = ["git", "-c", "user.name=arca", "-c", "user.email=arca@localhost"]


def info(gid):
    results = {r["id"]: r for r in json.load(open(os.path.join(G, "build.json")))}
    r = results.get(gid)
    if r is None:
        sys.exit(f"unknown game '{gid}'. Try: run.sh mod.py list")
    if not r.get("ok") or "build" not in r:
        sys.exit(f"{gid} does not build in this sandbox yet ({r.get('error') or r.get('log', '')[:120]}).\n"
                 f"Its source is in games/src/{gid}; the author's ROM is in games/roms/.")
    return r


def work_dir(gid):
    return os.path.join(G, "work", gid)


def git(gid, *args, **kw):
    return subprocess.run(GIT + list(args), cwd=work_dir(gid), **kw)


def init(gid):
    r = info(gid)
    w = work_dir(gid)
    if os.path.exists(w):
        sys.exit(f"{w} already exists (use 'reset' first to start over)")
    # 1. untouched source + the sandbox's automatic fixes = the baseline commit
    bg.prepare(os.path.join(G, "src", gid), w, gid, apply_patch=False)
    subprocess.run(["git", "init", "-q", w], check=True)
    git(gid, "add", "-A", check=True)
    git(gid, "commit", "-qm", "untouched source (plus sandbox build fixes)", check=True)
    helper = os.path.join(G, "build", gid, "_arca_build.sh")       # translated .bat / script, if any
    if os.path.exists(helper):
        shutil.copy(helper, w)
    # 2. any saved patch is applied on top, as uncommitted changes you keep editing
    patch = os.path.join(bg.PATCHES, gid + ".patch")
    if os.path.exists(patch):
        git(gid, "apply", "--index", "--whitespace=nowarn", patch, check=True)
        print(f"applied saved patch {os.path.relpath(patch, HERE)}")
    # 3. one build, noting which of the repo's own files the build rewrites (e.g. tile data
    #    regenerated from PNGs), so they are not mistaken for your edits later
    tracked = git(gid, "ls-files", "-z", capture_output=True, text=True).stdout.split("\0")
    tracked = [f for f in tracked if f and os.path.isfile(os.path.join(w, f))]
    before = {f: os.stat(os.path.join(w, f)).st_mtime_ns for f in tracked}
    print("first build ...")
    ok = run_recipe(gid, quiet=True)
    gen = {f: sha(os.path.join(w, f)) for f in tracked
           if os.path.isfile(os.path.join(w, f)) and os.stat(os.path.join(w, f)).st_mtime_ns != before[f]}
    json.dump(gen, open(os.path.join(w, ".git", "arca-generated.json"), "w"), indent=1)
    print(f"working copy: {w}\nbuilt with:   {r['toolchain']} ({'builds' if ok else 'FIRST BUILD FAILED'})"
          + (f"\n              {len(gen)} repo files are regenerated by the build; they stay out of your patch"
             if gen else "")
          + f"\nnext:         edit, then run.sh mod.py {gid} build")


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def run_recipe(gid, quiet=False):
    r = info(gid)
    env = dict(os.environ, **r["build"]["env"])
    if not quiet:
        print(f"$ {r['build']['cmd']}")
    p = subprocess.run(r["build"]["cmd"], cwd=work_dir(gid), env=env, shell=True,
                       capture_output=quiet)
    return p.returncode == 0 and bool(bg.roms_in(work_dir(gid)))


def build(gid):
    if not os.path.exists(work_dir(gid)):
        init(gid)
    ok = run_recipe(gid)
    roms = sorted(bg.roms_in(work_dir(gid)), key=os.path.getmtime)
    if not ok or not roms:
        sys.exit("build failed (see the output above)")
    print(f"\nROM: {roms[-1]}\nnext: run.sh mod.py {gid} play")
    return roms[-1]


def play(gid):
    w = work_dir(gid)
    roms = sorted(bg.roms_in(w), key=os.path.getmtime) if os.path.exists(w) else []
    rom = roms[-1] if roms else build(gid)
    exe = shutil.which("mgba-qt") or shutil.which("mgba")
    print(f"mGBA: {rom}")
    # Pace by the display, not the audio: WSLg's audio (a remote-desktop channel to Windows)
    # starves mGBA's default audio sync to ~1.5 fps. Video sync holds 60 fps.
    subprocess.Popen([exe, "-C", "audioSync=0", "-C", "videoSync=1", rom],
                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)


# Changes = edits to files that came with the source, plus new files you `git add` yourself.
# Files the build generates, or regenerates exactly as it did at init, are left out.
def stage(gid):
    w = work_dir(gid)
    git(gid, "add", "-u")
    gen_file = os.path.join(w, ".git", "arca-generated.json")
    gen = json.load(open(gen_file)) if os.path.exists(gen_file) else {}
    skip = [f for f, h in gen.items() if os.path.isfile(os.path.join(w, f)) and sha(os.path.join(w, f)) == h]
    if skip:
        git(gid, "reset", "-q", "--", *skip)


def diff(gid):
    stage(gid)
    git(gid, "diff", "--cached", "--stat")
    git(gid, "diff", "--cached")


def save_patch(gid):
    stage(gid)
    out = git(gid, "diff", "--cached", "--binary", capture_output=True).stdout
    path = os.path.join(bg.PATCHES, gid + ".patch")
    os.makedirs(bg.PATCHES, exist_ok=True)
    if not out.strip():
        if os.path.exists(path):
            os.remove(path)
        print("no changes: patch removed")
        return
    open(path, "wb").write(out)
    print(f"saved {path}\n05_build_games.py now applies it on every build")


def reset(gid):
    shutil.rmtree(work_dir(gid), ignore_errors=True)
    print(f"removed {work_dir(gid)}")


def list_games():
    for r in json.load(open(os.path.join(G, "build.json"))):
        mark = "modifiable" if r.get("ok") else "not built"
        edited = " (patched)" if os.path.exists(os.path.join(bg.PATCHES, r["id"] + ".patch")) else ""
        print(f"  {r['id']:28s} {mark:11s} {r.get('toolchain') or ''}{edited}")


def main():
    a = sys.argv[1:]
    if a[:1] == ["list"]:
        return list_games()
    if len(a) != 2:
        sys.exit(__doc__)
    gid, cmd = a
    {"init": init, "build": build, "play": play, "diff": diff, "patch": save_patch, "reset": reset}.get(
        cmd, lambda _: sys.exit(__doc__))(gid)


if __name__ == "__main__":
    main()
