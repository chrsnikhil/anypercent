"""Colour renders of the assembled handheld, via OpenSCAD's preview renderer
(which honours color() including alpha).

Run AFTER ../build_stl_viewer.ps1: colours come from
stl_assembly/assembly_colours.json, which that script writes from its
$AssemblyManifest, so these renders and the web viewer always agree.

    python cad2/render_coloured.py            # all shots
    python cad2/render_coloured.py front_34   # just one

Output: preview/coloured/*.png

Cameras are PROPER rotations only. No image is mirrored or flipped, so every
render shows the device exactly as it will print. (render.sh flips its front
views vertically after a 180 deg camera roll; a flip is a mirror, which puts
the D-pad on the wrong side of the picture.)

The model is rotated so device +y (up) is OpenSCAD +z, because the vector
camera always keeps +z up on screen:  device (x, y, z) -> world (x, -z, y).
"""
import json
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OPENSCAD = r"C:\Program Files\OpenSCAD\openscad.exe"
ASM = os.path.join(HERE, "stl_assembly")
OUT = os.path.join(HERE, "preview", "coloured")
CENTRE = (101.0, 62.0, 21.7)       # device-space centre of the assembly


def cam(yaw, pitch):
    """Viewer-style angles. yaw 0 looks at the REAR (+z), yaw pi at the FRONT.
    Returns a unit direction from the device centre to the eye, device space."""
    return (math.sin(yaw) * math.cos(pitch), math.sin(pitch), math.cos(yaw) * math.cos(pitch))


# name: (panel fitted, eye direction in device space, projection, image size)
SHOTS = {
    "front_34":           ("world", cam(math.pi + 0.62, 0.32), "p"),
    "front_straight":     ("world", cam(math.pi, 0.0),          "o"),
    "rear_34_world":      ("world", cam(0.62, 0.32),            "p"),
    "rear_34_arkiv":      ("arkiv", cam(0.62, 0.32),            "p"),
    "rear_34_arc":        ("arc",   cam(0.62, 0.32),            "p"),
    "rear_straight_world": ("world", cam(0.0, 0.0),             "o"),
    "rear_straight_arkiv": ("arkiv", cam(0.0, 0.0),             "o"),
    "rear_straight_arc":  ("arc",   cam(0.0, 0.0),              "o"),
}


def to_world(v):
    x, y, z = v
    return (x, -z, y)


def rgba(hex_colour, alpha):
    h = hex_colour.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return f"[{r:.4f}, {g:.4f}, {b:.4f}, {alpha:.3f}]"


def scad_for(parts, panel):
    # Only ONE rear panel: the three share a plate at identical depth.
    keep = [p for p in parts
            if not p["group"].startswith("panel:") or p["group"] == f"panel:{panel}"]
    # Opaque first, translucent last. OpenSCAD's preview draws in tree order
    # with depth writes on, so a translucent part listed first would blank out
    # everything behind it.
    keep.sort(key=lambda p: p["alpha"] < 1)
    lines = ["// generated by render_coloured.py - do not edit",
             "rotate([90, 0, 0]) {"]
    for p in keep:
        path = os.path.join(ASM, p["file"]).replace("\\", "/")
        lines.append(f'  color({rgba(p["colour"], p["alpha"])}) import("{path}");  // {p["label"]}')
    lines.append("}")
    return "\n".join(lines) + "\n", keep


def main(only):
    with open(os.path.join(ASM, "assembly_colours.json"), encoding="utf-8") as f:
        manifest = json.load(f)
    parts = manifest["parts"]
    os.makedirs(OUT, exist_ok=True)
    centre_w = to_world(CENTRE)
    for name, (panel, eye_dir, proj) in SHOTS.items():
        if only and name not in only:
            continue
        src, keep = scad_for(parts, panel)
        scad = os.path.join(OUT, f"_{name}.scad")
        with open(scad, "w", encoding="utf-8") as f:
            f.write(src)
        d = to_world(eye_dir)
        eye = [c + 400.0 * k for c, k in zip(centre_w, d)]
        camera = ",".join(f"{v:.3f}" for v in eye + list(centre_w))
        png = os.path.join(OUT, f"{name}.png")
        cmd = [OPENSCAD, "-o", png, "--imgsize=1600,1200", f"--projection={proj}",
               f"--camera={camera}", "--viewall", "--colorscheme=Tomorrow", scad]
        r = subprocess.run(cmd, capture_output=True, text=True)
        os.remove(scad)
        bad = [l for l in (r.stdout + r.stderr).splitlines() if "WARNING" in l or "ERROR" in l]
        panels = sorted({p["group"] for p in keep if p["group"].startswith("panel:")})
        print(f"{'OK ' if r.returncode == 0 and not bad else 'ERR'} {name:<22} panel={','.join(panels):<12} "
              f"{len(keep)} parts -> {os.path.relpath(png, HERE)}")
        for l in bad:
            print("    ", l)


if __name__ == "__main__":
    main(set(sys.argv[1:]))
