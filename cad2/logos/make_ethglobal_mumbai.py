"""Split the official ETHGlobal Mumbai logomark (ethglobal_mumbai_logomark.svg, from ethglobal.com/events/mumbai)
into one SVG per path, all with the same viewBox and millimetre size so they import into OpenSCAD in register,
plus groups.scad: each path's colour group, in painting order (a later path covers an earlier one).

Six source colours are merged into three filament groups so the panel fits one 4-slot AMS with its body:
  orange = rays + flame (#FFAE00, #FF8500, #FF6C00), pink = lamp (#FC2081, #AD0041), green = base (#00B88E)."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "ethglobal_mumbai_logomark.svg")
OUT = os.path.join(HERE, "ethglobal_mumbai")
HEIGHT_MM = 88.0                                       # emblem height on the 124 mm panel
GROUP = {"#FFAE00": "orange", "#FF8500": "orange", "#FF6C00": "orange",
         "#FC2081": "pink", "#AD0041": "pink", "#00B88E": "green"}
# the complete logo, every source colour its own filament (the burgundy panel)
FULL = {"#FFAE00": "yellow", "#FF8500": "orange", "#FF6C00": "flame",
        "#FC2081": "pink", "#AD0041": "red", "#00B88E": "green"}

s = open(SRC, encoding="utf-8").read()
vb = [float(v) for v in re.search(r'viewBox="([^"]*)"', s).group(1).split()]
w_mm = HEIGHT_MM * vb[2] / vb[3]
paths = re.findall(r"<path\b[^>]*>", s)
groups, full = [], []
for i, p in enumerate(paths):
    d = re.search(r'\sd="([^"]*)"', p).group(1)
    fill = re.search(r'fill="([^"]*)"', p).group(1).upper()
    groups.append(GROUP[fill])
    full.append(FULL[fill])
    with open(os.path.join(OUT, f"p{i:02d}.svg"), "w", encoding="utf-8") as fh:
        fh.write(f'<svg xmlns="http://www.w3.org/2000/svg" width="{w_mm:.4f}mm" height="{HEIGHT_MM:.4f}mm" '
                 f'viewBox="{" ".join(f"{v:g}" for v in vb)}"><path d="{d}" fill="#000"/></svg>\n')
with open(os.path.join(OUT, "groups.scad"), "w", encoding="utf-8") as fh:
    fh.write("// generated by logos/make_ethglobal_mumbai.py\n")
    fh.write(f"eth_mumbai_w = {w_mm:.4f};\neth_mumbai_h = {HEIGHT_MM:.4f};\n")
    fh.write("eth_mumbai_groups = [" + ", ".join(f'"{g}"' for g in groups) + "];\n")
    fh.write("eth_mumbai_colours = [" + ", ".join(f'"{g}"' for g in full) + "];\n")
print(len(paths), "paths;", {g: groups.count(g) for g in set(groups)}, f"{w_mm:.1f} x {HEIGHT_MM} mm")
