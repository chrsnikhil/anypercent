"""Split the official ETHGlobal Mumbai lockup (ethglobal_mumbai_lockup.svg: the diya plus the "ETHGlobal MUMBAI"
wordmark, from ethglobal.com/events/mumbai) into one SVG per path, all with the same viewBox and millimetre size so
they import into OpenSCAD in register, plus groups.scad with each path's colour, in painting order.

Every source colour is its own filament: with the cream plate that is 8, i.e. two 4-slot AMS units."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "ethglobal_mumbai_lockup.svg")
OUT = os.path.join(HERE, "ethglobal_mumbai_lockup")
WIDTH_MM = 182.0                                       # across the 202 mm panel
COLOUR = {"#FFAE00": "yellow", "#FF8500": "orange", "#FF6C00": "flame", "#FC2081": "pink",
          "#AD0041": "red", "#00B88E": "green", "#7A0032": "burgundy"}
# the same logo on the spools the owner's printer has, in 4 AMS slots: the yellow rays print orange too
SPOOL = {"yellow": "orange", "orange": "orange", "flame": "orange", "pink": "red", "red": "red",
         "green": "green", "burgundy": "red"}

s = open(SRC, encoding="utf-8").read()
fills, rules = {}, {}
for sel, body in re.findall(r"([.\w\-, ]+)\{([^}]*)\}", s):
    for cls in re.findall(r"\.(cls-\d+)", sel):
        m = re.search(r"fill:\s*(#[0-9a-fA-F]{6})", body)
        if m:
            fills[cls] = m.group(1).upper()
        m = re.search(r"fill-rule:\s*(\w+)", body)
        if m:
            rules[cls] = m.group(1)
vb = [float(v) for v in re.search(r'viewBox="([^"]*)"', s).group(1).split()]
h_mm = WIDTH_MM * vb[3] / vb[2]
os.makedirs(OUT, exist_ok=True)
colours = []
for i, p in enumerate(re.findall(r"<path\b[^>]*>", s)):
    cls = re.search(r'class="([^"]*)"', p).group(1)
    d = re.search(r'\sd="([^"]*)"', p).group(1)
    colours.append(COLOUR[fills[cls]])
    rule = f' fill-rule="{rules[cls]}"' if cls in rules else ""
    with open(os.path.join(OUT, f"p{i:02d}.svg"), "w", encoding="utf-8") as fh:
        fh.write(f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH_MM:.4f}mm" height="{h_mm:.4f}mm" '
                 f'viewBox="{" ".join(f"{v:g}" for v in vb)}"><path d="{d}" fill="#000"{rule}/></svg>\n')
with open(os.path.join(OUT, "groups.scad"), "w", encoding="utf-8") as fh:
    fh.write("// generated by logos/make_ethglobal_mumbai_lockup.py\n")
    fh.write(f"eth_lockup_w = {WIDTH_MM:.4f};\neth_lockup_h = {h_mm:.4f};\n")
    fh.write("eth_lockup_colours = [" + ", ".join(f'"{c}"' for c in colours) + "];\n")
    fh.write("eth_lockup_spools = [" + ", ".join(f'"{SPOOL[c]}"' for c in colours) + "];\n")
print(len(colours), "paths;", {c: colours.count(c) for c in dict.fromkeys(colours)}, f"{WIDTH_MM} x {h_mm:.1f} mm;",
      "even-odd:", [i for i, p in enumerate(re.findall(r"<path\b[^>]*>", s)) if re.search(r'class="([^"]*)"', p).group(1) in rules])
