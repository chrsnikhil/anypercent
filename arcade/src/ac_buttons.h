/* GBA keypad bits in KEYINPUT order (active high here). */
#ifndef AC_BUTTONS_H
#define AC_BUTTONS_H
#define BTN_A      0x001
#define BTN_B      0x002
#define BTN_SELECT 0x004
#define BTN_START  0x008
#define BTN_RIGHT  0x010
#define BTN_LEFT   0x020
#define BTN_UP     0x040
#define BTN_DOWN   0x080
#define BTN_R      0x100
#define BTN_L      0x200
#define BTN_MASK   0x3FF
#endif
