"""Write ac_tables.c: the quarter-wave sine table (257 entries, Q1.14) and the atan table (257 entries,
angle steps of 1024 per turn for ratios 0..1 in 1/256 steps). Integers only, so every target agrees."""
import math

print("/* Generated by tools/gen_tables.py. Do not edit. */")
print("#include <stdint.h>")
sin = [round(math.sin(i / 256 * math.pi / 2) * 16384) for i in range(257)]
print("const int16_t ac_sin_q[257] = {" + ",".join(map(str, sin)) + "};")
atn = [round(math.atan(i / 256) / (2 * math.pi) * 1024) for i in range(257)]
print("const uint16_t ac_atan_t[257] = {" + ",".join(map(str, atn)) + "};")
